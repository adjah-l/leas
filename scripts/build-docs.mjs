// The operator's manual is the source of truth for docs content.
// This lifts each section out of it into a module the site renders.
import { readFileSync, writeFileSync } from 'node:fs';

const html = readFileSync('leas-operators-manual.html', 'utf8');
const sections = [];
const re = /<section id="([^"]+)">([\s\S]*?)<\/section>/g;
let m;
while ((m = re.exec(html))) {
  const [, slug, inner] = m;
  const head = /<div class="sec-head"><span class="sec-num">([^<]+)<\/span><h2>([\s\S]*?)<\/h2><\/div>/.exec(inner);
  if (!head) continue;
  sections.push({
    slug,
    num: head[1],
    title: head[2].replace(/&amp;/g, '&').trim(),
    body: inner.slice(head.index + head[0].length).trim(),
  });
}

// A one-line summary per section, for the docs index cards.
const blurbs = {
  model: 'How the three pieces fit together, and why local and cloud are one code path.',
  accounts: 'The five accounts you need, what each costs, and which one has a week-long delay.',
  setup: 'Ten numbered steps from an empty project to a signed build in the store.',
  daily: 'The commands you will actually use, and which profile to reach for.',
  dash: 'Watching builds and updates in real time.',
  updates: 'Shipping a JavaScript fix to devices already in the field.',
  identity: 'Where login lives today, and what each credential proves.',
  rotate: 'Five runbooks for replacing a key without breaking your builds.',
  org: 'Moving the app to a different Apple team, Play account, or GitHub org.',
  people: 'Giving someone access without handing over any keys.',
  broken: 'The failures you will meet, and the fix for each.',
  market: 'What turning this into a product other companies pay for actually requires.',
  ref: 'Environment variables, file map, and implementation notes.',
};

const out = `// GENERATED by scripts/build-docs.mjs — edit leas-operators-manual.html instead.
export type DocSection = { slug: string; num: string; title: string; blurb: string; body: string };

export const docs: DocSection[] = ${JSON.stringify(
  sections.map((s) => ({ ...s, blurb: blurbs[s.slug] ?? '' })), null, 2)};

export const bySlug = (slug: string) => docs.find((d) => d.slug === slug);
`;
writeFileSync('site/lib/docs.ts', out);
console.log(`extracted ${sections.length} sections → site/lib/docs.ts (${(out.length/1024).toFixed(0)} KB)`);
for (const s of sections) console.log(`  ${s.num}  ${s.slug.padEnd(10)} ${s.title}`);
