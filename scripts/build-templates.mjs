// The workflow templates in templates/ are the source of truth. This lifts them
// into a module the site can embed, because Vercel builds from site/ and cannot
// read files above it. Same arrangement as scripts/build-docs.mjs.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import path from 'node:path';

const DIR = 'templates';
const files = readdirSync(DIR).filter((f) => f.endsWith('.yml')).sort();

const entries = files.map((f) => {
  const name = path.basename(f, '.yml');
  return `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(path.join(DIR, f), 'utf8'))},`;
});

writeFileSync('site/lib/templates.ts', `// GENERATED by scripts/build-templates.mjs — edit templates/*.yml instead.
export const templates: Record<string, string> = {
${entries.join('\n')}
};
`);

console.log(`embedded ${files.length} template(s) → site/lib/templates.ts`);
for (const f of files) console.log(`  ${f}`);
